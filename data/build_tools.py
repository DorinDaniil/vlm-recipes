# ── сборка ────────────────────────────────────────────────────────────


def trajectory(group: str, ask: str, calls: list[Call], answer: str) -> dict:
    rendered = "\n".join(toolcalls.render_call(n, a, style=STYLE) for n, a, _ in calls)
    messages = [user(ask), assistant(rendered)]
    messages += [tool(r) for _, _, r in calls]
    messages.append(assistant(answer))

    # Круговая проверка: то, что записали, обязано разбираться обратно.
    parsed = toolcalls.parse_tool_calls(rendered)
    assert [(c["name"], c["arguments"]) for c in parsed] == [(n, a) for n, a, _ in calls], ask

    return {"group": group, "expected": [r for _, _, r in calls], "messages": messages}


def main() -> None:
    rows = []
    rows += [trajectory("tool", *calc_case()) for _ in range(30)]
    rows += [trajectory("tool", *words_case()) for _ in range(15)]
    rows += [trajectory("tool", *reverse_case()) for _ in range(15)]
    rows += [trajectory("multi", *multi_case()) for _ in range(16)]
    rows += [
        {"group": "direct", "expected": None, "messages": [user(q), assistant(a)]}
        for q, a in DIRECT
    ]
    rng.shuffle(rows)

    out = Path(__file__).with_name("tools.jsonl")
    with out.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")

    counts = {g: sum(r["group"] == g for r in rows) for g in ("tool", "multi", "direct")}
    print(f"{out.name}: {len(rows)} строк, {counts}, формат {STYLE}")


if __name__ == "__main__":
    main()
