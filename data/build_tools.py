def build() -> list[dict]:
    records = []

    for question, name, arguments, result, final in TOOL_CASES:
        records.append({
            "group": "tool", "expect_tool": name,
            "messages": [system(), user(question), tool_call(name, arguments),
                         tool_result(result), assistant(final)],
        })

    for question, answer in DIRECT_CASES:
        records.append({
            "group": "direct", "expect_tool": None,
            "messages": [system(), user(question), assistant(answer)],
        })

    for question, name, arguments, result, final in STOP_CASES:
        records.append({
            "group": "stop", "expect_tool": name,
            "messages": [system(), user(question), tool_call(name, arguments),
                         tool_result(result), assistant(final)],
        })

    for question, n1, a1, r1, n2, a2, r2, final in MULTI_CASES:
        records.append({
            "group": "multi", "expect_tool": n1,
            "messages": [system(), user(question),
                         tool_call(n1, a1), tool_result(r1),
                         tool_call(n2, a2), tool_result(r2),
                         assistant(final)],
        })

    for question, name, arguments, result, final in EMPTY_CASES:
        records.append({
            "group": "empty", "expect_tool": name,
            "messages": [system(), user(question), tool_call(name, arguments),
                         tool_result(result), assistant(final)],
        })

    return records


