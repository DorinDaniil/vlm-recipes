# Модуль подгружается по пути, а не через `from vlmkit.toolcalls import`:
# пакет при импорте тянет transformers и torch, а сборке данных они
# не нужны. Сам toolcalls зависит только от стандартной библиотеки.
_path = Path(__file__).resolve().parents[1] / "vlmkit" / "toolcalls.py"
_spec = importlib.util.spec_from_file_location("toolcalls", _path)
_toolcalls = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_toolcalls)
render_call = _toolcalls.render_call

#: Формат вызова обязан совпадать с тем, которого ждёт шаблон вашей
#: модели, иначе вы учите её одному, а обвязка разбирает другое.
#: Посмотреть: detect_style(processor.tokenizer.chat_template)
STYLE = "xml"

TOOLS = """Доступные инструменты:
- select_skill(name): методика работы с классом задач
- read_document(section_id): текст раздела работы
- search_sources(query): поиск по научной базе
- read_source(source_id): текст источника
- search_chat_history(query): поиск по прошлым сообщениям"""


def user(text: str) -> dict:
    return {"role": "user", "content": [{"type": "text", "text": text}]}


def assistant(text: str) -> dict:
    return {"role": "assistant", "content": [{"type": "text", "text": text}]}


def tool_call(name: str, arguments: dict) -> dict:
    # arguments передаётся словарём, а не **kwargs: у select_skill есть
    # собственный аргумент name, и он затирал бы имя инструмента.
    return assistant(render_call(name, arguments, style=STYLE))


def tool_result(text: str) -> dict:
    return {"role": "tool", "content": [{"type": "text", "text": text}]}


def system() -> dict:
    return {"role": "system", "content": [{"type": "text", "text": TOOLS}]}


