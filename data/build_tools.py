WORDS = [
    "диплом", "гипотеза", "антиплагиат", "методология", "кафедра", "литература",
    "защита", "выборка", "апробация", "нормоконтроль", "рецензия", "актуальность",
]


def words_case() -> tuple[str, list[Call], str]:
    phrase = rng.choice(PHRASES)
    n = toy.word_count(phrase)
    ask = rng.choice([f"Сколько слов в фразе «{phrase}»?", f"Посчитай слова: «{phrase}»."])
    return ask, [("word_count", {"text": phrase}, n)], f"В этой фразе {n} слов."


def reverse_case() -> tuple[str, list[Call], str]:
    word = rng.choice(WORDS)
    rev = toy.reverse(word)
    ask = rng.choice([f"Переверни слово «{word}».", f"Напиши слово «{word}» наоборот."])
    return ask, [("reverse", {"text": word}, rev)], f"Наоборот: «{rev}»."


def multi_case() -> tuple[str, list[Call], str]:
    (_, c1, _), (_, c2, _) = calc_case(), calc_case()
    e1, e2 = c1[0][1]["expression"], c2[0][1]["expression"]
    ask = rng.choice([f"Посчитай два выражения: {e1} и {e2}.", f"Мне нужно {e1} и ещё {e2}."])
    return ask, c1 + c2, f"{e1} = {c1[0][2]}, {e2} = {c2[0][2]}."


