"""Сборка траекторий с игрушечными инструментами в tools.jsonl.

Пишется скриптом: инструменты исполняются по-настоящему, поэтому
результаты в траекториях верные, а в каждой строке лежит `expected` —
значения, которые должны оказаться в конечном ответе агента.

    tool    без инструмента не ответить: вызов → результат → ответ
    multi   два вызова за один ход
    direct  ответ известен и так, инструмент не нужен

Без третьей группы модель выучит «дёргать инструмент всегда».
"""

from __future__ import annotations

