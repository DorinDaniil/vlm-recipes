"""Сборка агентских траекторий в tools.jsonl.

Пишется скриптом, а не руками: вызов инструмента — это JSON внутри JSON,
и ручное экранирование ломается на третьей записи.

Пять групп. Первая учит вызывать, остальные четыре — не вызывать лишнего,
останавливаться, продолжать цепочку и справляться с пустым результатом.
Выборка из одних успешных вызовов даёт модель, которая дёргает
инструменты постоянно и не умеет останавливаться.

    tool    инструмент вызвать нужно
    direct  ответ уже в контексте, вызывать НЕ нужно
    stop    результат получен, пора отвечать
    multi   одного вызова мало, нужна цепочка
    empty   инструмент вернул пусто или ошибку
"""

